"""Ядро t-распределения против scipy.

scipy здесь только оракул: рантайм от него не зависит. Смысл в том,
что две независимые реализации дают основание доверять числу, а одна,
взятая на веру, — нет. Именно эта сверка поймала расхождение в
префакторе неполной беты (docs/ARCHITECTURE.md, 8.3).
"""

import math
import random

import pytest

from statverify.tstats import df_from, p_normal_limit, p_two_tailed, t_from_p

sps = pytest.importorskip("scipy.stats", reason="scipy — оракул, нужен только тестам")

# Порог выведен из требования задачи, а не подогнан под результат.
# Самое узкое сравнение в L4 — интервал при четырёх знаках после
# запятой, полуширина 5e-5. Требуем тысячекратный запас.
TOLERANCE_P = 5e-5 / 1000


def test_p_two_tailed_matches_scipy():
    rng = random.Random(20260910)
    worst = 0.0
    for _ in range(4000):
        df = rng.choice([1, 2, 3, 5, 8, 13, 24, 45.3, 99, 250, 1000, 10000])
        t = rng.uniform(0.0, 8.0)
        ref = 2.0 * sps.t.sf(abs(t), df)
        worst = max(worst, abs(p_two_tailed(t, df) - ref) / max(ref, 1e-300))
    assert worst < TOLERANCE_P, f"расхождение с scipy {worst:.3e}"


def test_t_from_p_matches_scipy():
    rng = random.Random(4242)
    for _ in range(300):
        df = rng.choice([3, 10, 30, 99, 500])
        p = 10 ** rng.uniform(-6, -0.05)
        got, ref = t_from_p(p, df), sps.t.isf(p / 2.0, df)
        assert got is not None
        assert abs(got - ref) / ref < 1e-9


def test_t_crit_matches_scipy():
    """t_from_p(alpha, df) — критическое значение для доверительного
    интервала. На этом будет строиться отношение R4."""
    for df in (10, 24, 99, 250):
        assert abs(t_from_p(0.05, df) - sps.t.ppf(0.975, df)) < 1e-12


def test_df_from_is_inverse():
    for df in (5, 20, 99, 300):
        for t in (1.5, 2.45, 3.2, 5.0):
            p = p_two_tailed(t, df)
            back = df_from(t, p)
            assert back is not None
            assert abs(p_two_tailed(t, back) - p) / p < 1e-9


@pytest.mark.parametrize("t", [1.0, 1.96, 2.45, 3.0, 4.0])
def test_normal_limit_matches_scipy(t):
    """Сам предел обязан совпасть с 2*(1-Φ(|t|)) по независимому оракулу,
    не только с тем, что возвращает p_normal_limit сам себе."""
    ref = 2.0 * (1.0 - sps.norm.cdf(abs(t)))
    assert abs(p_normal_limit(t) - ref) < 1e-12


# Допуск на боковое проседание НИЖЕ предела — не ноль: у p_two_tailed
# уже задокументирована (tstats.py, докстринг модуля) потеря точности на
# больших df из-за вычитания близких lgamma, до ~1e-10 относительных
# против scipy напрямую, а вблизи собственной асимптоты той же величины
# вычитание ещё чувствительнее. Измерено явно (не подобрано под тест):
# худшее наблюдаемое проседание по сетке ниже — 8.5e-7 относительных
# (t=1.96, df=1e9). Порог берёт более чем десятикратный запас над этим
# измеренным профилем шума — достаточно тесный, чтобы ЛЮБАЯ подмена
# предела на неверную константу (в частности 0.0) была поймана с
# огромным запасом, и достаточно свободный, чтобы не спотыкаться о
# собственный документированный шум ядра.
REL_FLOOR_SLACK = 1e-5


@pytest.mark.parametrize("t", [1.0, 1.96, 2.45, 3.0, 4.0])
def test_normal_limit_is_a_floor_and_is_approached(t):
    """Двусторонний p не опускается ниже предела (с учётом собственного
    численного шума ядра) ни при каком df — и, что здесь главное,
    действительно к нему СХОДИТСЯ с ростом df, а не просто держится не
    ниже произвольной константы.

    Прежняя версия этого теста проверяла только одностороннюю границу
    'p_two_tailed(t, df) >= limit - 1e-15' — при подмене p_normal_limit
    на 'return 0.0' это условие тождественно истинно (p_two_tailed
    всегда >= 0), и мутация проходила незамеченной. Проверка на
    сходимость ловит эту мутацию: при limit=0 относительная невязка на
    df=1e9 не уйдёт к нулю, она останется порядка единицы.
    """
    limit = p_normal_limit(t)
    assert limit > 0.0, "предел обязан быть положительным для любого конечного t"

    for df in (1, 5, 50, 1000, 100000, 1_000_000, 1e8, 1e9):
        p = p_two_tailed(t, df)
        assert p >= limit * (1.0 - REL_FLOOR_SLACK), (
            f"df={df}: {p} заметно ниже предела {limit} — больше, чем "
            f"объясняется документированным шумом ядра")

    # Главное числовое требование: на очень большом df относительная
    # невязка обязана быть исчезающе малой — это и есть "сходится", а
    # не "не опускается ниже". При limit=0 (мутация) это отношение либо
    # не определено (деление на ноль), либо порядка единицы — тест падает.
    huge_df_gap = p_two_tailed(t, 1e9) - limit
    assert abs(huge_df_gap) / limit < REL_FLOOR_SLACK, (
        f"относительная невязка на df=1e9 составляет "
        f"{huge_df_gap/limit:.3e} — предел не сходится")


@pytest.mark.parametrize("t", [1.0, 1.96, 2.45, 3.0, 4.0])
def test_df_from_rejects_target_below_normal_limit(t):
    """Цель строго внутри (0, 1), но ниже нормального предела —
    недостижима ни при каком df, ответ обязан быть None.

    Порог для p вычислен НЕЗАВИСИМО (через scipy, тот же оракул, что и
    в остальном файле), не через p_normal_limit: иначе тест был бы
    завязан на ту же функцию, которую отчасти проверяет, и не отличил
    бы верный предел от мутированного. Прежняя версия домножала
    p_normal_limit(t) на 0.5 — при подмене предела на 'return 0.0' цель
    становилась равна 0.0 и отсекалась более ранней проверкой
    'not (0.0 < p < 1.0)', то есть тест проходил по чужой причине.
    Домножение здесь оставлено намеренно тем же (0.5) — важна не
    формула, а источник эталонного предела.

    ЧЕСТНАЯ ОГОВОРКА, а не молчаливое исправление: мутация 'df_from без
    проверки \"if p < p_normal_limit(t): return None\"' на этой
    реализации — ЭКВИВАЛЕНТНАЯ, её нельзя поймать никаким тестом на
    результат df_from. Причина: без явной проверки функция всё равно
    возвращает None через страховочный срез по df_max — при p ниже
    истинного предела p_two_tailed(t, df_max) всегда СТРОГО ВЫШЕ p
    (предел приближается сверху и не достигается ни при каком конечном
    df, проверено численно для t от 1 до 8: p_two_tailed(t, 1e7) —
    p_normal_limit(t) всегда положительна), поэтому бинарный поиск
    всегда сходится к df_max и упирается в 'return None if out >=
    df_max * 0.999'. Убранная строка — чистая оптимизация (мгновенный
    отказ вместо 300 итераций бисекции впустую), не источник различимого
    поведения. Тест ниже всё равно ценен: он проверяет СВОЙСТВО
    (отказ на недостижимой цели) независимым эталоном, а не то, что
    именно эта строка присутствует в файле, — это защитит от РЕАЛЬНОЙ
    порчи (перепутанный знак сравнения, неверный источник предела),
    просто не от этой конкретной, ничего не меняющей.
    """
    true_limit = 2.0 * (1.0 - sps.norm.cdf(abs(t)))
    p = true_limit * 0.5
    assert 0.0 < p < 1.0, "цель обязана быть строго внутри (0,1) для этого теста"
    assert df_from(t, p) is None


@pytest.mark.parametrize("t,df,want", [(1.96, 1e7, 0.05), (2.0, 60, 0.0500),
                                       (2.45, 99, 0.01604)])
def test_reference_values(t, df, want):
    assert math.isclose(p_two_tailed(t, df), want, rel_tol=5e-3)
