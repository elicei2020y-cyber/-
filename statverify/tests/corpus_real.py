def dev() -> List[Dict[str, Any]]:
    """Рабочая половина: по ней разрешено чинить код."""
    return [r for r in CORPUS_REAL if r["split"] == "dev"]


def holdout() -> List[Dict[str, Any]]:
    """Отложенная половина: прогоняется один раз, по ней не чинится ничего."""
    return [r for r in CORPUS_REAL if r["split"] == "holdout"]


def with_t_test(rows=None) -> List[Dict[str, Any]]:
    return [r for r in (rows or CORPUS_REAL) if r["has_t_test"]]


def genuine_mismatches(rows=None) -> List[Dict[str, Any]]:
    """Расхождения, не объяснимые печатью порога, — настоящие кандидаты."""
    return [r for r in with_t_test(rows)
            if not r["consistent"] and not r["floor_convention"]]
